/* squad.js — renders docs/roster.html's senior-squad sections from
   SQUAD_DATA (assets/squad_data.js, generated by scripts/sync_squad_page.py)
   and SQUAD_CONFIG (assets/squad_config.js, hand-curated editorial picks).
   Plain script, no build step — same pattern as home.js. Runs on
   DOMContentLoaded so it also works opened directly as a file://. */
(function () {
  'use strict';

  function el(tag, className, html) {
    var e = document.createElement(tag);
    if (className) e.className = className;
    if (html !== undefined) e.innerHTML = html;
    return e;
  }

  function esc(s) {
    return String(s).replace(/[&<>"']/g, function (c) {
      return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c];
    });
  }

  function placeholderSvg() {
    return '<svg viewBox="0 0 80 88" xmlns="http://www.w3.org/2000/svg" aria-hidden="true">' +
      '<path d="M26,10 L8,14 L0,38 L16,45 L16,82 L64,82 L64,45 L80,38 L72,14 L54,10 L48,12 L40,24 L32,12 Z" ' +
      'fill="currentColor" opacity="0.35"/></svg>';
  }

  function media(cls, player, eager) {
    var wrap = el('div', cls);
    if (player.image) {
      var img = el('img');
      img.src = player.image;
      img.alt = player.name;
      img.loading = eager ? 'eager' : 'lazy';
      img.width = 320; img.height = 400;
      wrap.appendChild(img);
    } else {
      wrap.appendChild(el('div', 'squad-card-placeholder', placeholderSvg()));
    }
    return wrap;
  }

  function positionLabel(player) {
    return player.positions.join(' / ');
  }

  function seasonLine(player) {
    if (!player.season) return null;
    var s = player.season;
    return s.apps + ' APP' + (s.apps === 1 ? '' : 'S') + ' &middot; ' + s.goals + ' G &middot; ' + s.assists + ' A';
  }

  /* ── Squad At a Glance ─────────────────────────────────────────────── */
  function renderGlance(root, data) {
    var g = data.glance;
    var stats = [
      { value: g.squadSize, label: 'Squad Size' },
      { value: g.avgAge, label: 'Average Age' },
      { value: g.avgOvr, label: 'Average OVR', gold: true },
      g.captain ? { value: g.captain, label: 'Captain', small: true } : null,
      g.topScorer ? { value: g.topScorer, label: 'Top Scorer', sub: g.topScorerGoals + ' goals', small: true } : null,
      g.mostAssists ? { value: g.mostAssists, label: 'Most Assists', sub: g.mostAssistsValue + ' assists', small: true } : null,
      { value: g.highestOvrValue, label: 'Highest OVR', sub: g.highestOvr, gold: true },
    ].filter(Boolean);

    stats.forEach(function (s) {
      var cell = el('div', 'squad-glance-stat');
      var valueClass = 'squad-glance-value' + (s.gold ? ' is-gold' : '');
      var valEl = el('div', valueClass, esc(s.value));
      if (s.small) valEl.style.fontSize = '22px';
      cell.appendChild(valEl);
      cell.appendChild(el('div', 'squad-glance-label', esc(s.label)));
      if (s.sub) cell.appendChild(el('div', 'squad-glance-sub', esc(s.sub)));
      root.appendChild(cell);
    });
  }

  /* ── Featured Player (reuses homepage .player-feature component) ──── */
  function renderFeatured(root, data) {
    var p = data.featured;
    if (!p) { root.style.display = 'none'; return; }

    var feature = el('div', 'player-feature');
    feature.appendChild(media('player-feature-media', p, true));

    var body = el('div', 'player-feature-body');
    body.appendChild(el('span', 'player-feature-kicker', 'Squad Spotlight'));
    body.appendChild(el('div', 'player-feature-name', esc(p.name)));

    var facts = el('div', 'player-feature-facts');
    var factList = [
      ['Position', positionLabel(p)],
      ['Age', p.age],
      p.height ? ['Height', p.height] : null,
      ['OVR', p.ovr],
      p.squadRole ? ['Role', p.squadRole] : null,
    ].filter(Boolean);
    factList.forEach(function (f) {
      facts.appendChild(el('span', null, '<strong>' + esc(f[1]) + '</strong>' + esc(f[0])));
    });
    facts.className += factList.length === 4 ? ' player-feature-facts-4' : '';
    body.appendChild(facts);

    if (p.season) {
      var seasonWrap = el('div', 'player-feature-season');
      seasonWrap.appendChild(el('span', 'player-feature-season-label', data.season + ' Season'));
      var seasonStats = el('div', 'player-feature-season-stats');
      [['Goals', p.season.goals], ['Assists', p.season.assists], ['Avg Rating', p.season.rating]].forEach(function (f) {
        seasonStats.appendChild(el('span', null, '<strong>' + esc(f[1]) + '</strong>' + esc(f[0])));
      });
      seasonWrap.appendChild(seasonStats);
      body.appendChild(seasonWrap);
    }

    feature.appendChild(body);
    root.appendChild(feature);
  }

  /* ── Position groups ───────────────────────────────────────────────── */
  var GROUP_ORDER = ['Goalkeepers', 'Defenders', 'Midfielders', 'Forwards'];

  function squadCard(p) {
    var card = el('div', 'squad-card');
    var m = media('squad-card-media', p, false);
    var ovrClass = 'squad-card-ovr' + (p.ovr >= 74 ? ' is-elite' : '');
    m.appendChild(el('span', ovrClass, esc(p.ovr)));
    if (p.captain) m.appendChild(el('span', 'squad-card-captain', 'C'));
    card.appendChild(m);

    var body = el('div', 'squad-card-body');
    if (p.squadRole) body.appendChild(el('span', 'squad-card-status', esc(p.squadRole)));
    body.appendChild(el('div', 'squad-card-name', esc(p.name) + (p.captain ? ' <span style="color:var(--gold)">(C)</span>' : '')));
    body.appendChild(el('div', 'squad-card-meta', esc(positionLabel(p))));

    var bioBits = [p.age + ' yrs'];
    if (p.height) bioBits.push(esc(p.height));
    body.appendChild(el('div', 'squad-card-bio', bioBits.join(' &middot; ')));

    var sl = seasonLine(p);
    if (sl) body.appendChild(el('div', 'squad-card-stats', sl));

    card.appendChild(body);
    return card;
  }

  function renderGroups(root, data) {
    var active = data.players.filter(function (p) { return !p.loan; });
    GROUP_ORDER.forEach(function (groupName) {
      var players = active.filter(function (p) { return p.group === groupName; })
        .sort(function (a, b) { return b.ovr - a.ovr; });
      if (!players.length) return;

      var section = el('div', 'squad-group');
      var head = el('div', 'squad-group-head');
      head.appendChild(el('h3', null, groupName));
      head.appendChild(el('span', 'squad-group-count', players.length + ' player' + (players.length === 1 ? '' : 's')));
      head.appendChild(el('span', 'squad-group-line'));
      section.appendChild(head);

      var grid = el('div', 'squad-grid');
      players.forEach(function (p) { grid.appendChild(squadCard(p)); });
      section.appendChild(grid);
      root.appendChild(section);
    });
  }

  /* ── Loan Watch ─────────────────────────────────────────────────────── */
  function renderLoanWatch(section, root, data) {
    var loaned = data.players.filter(function (p) { return p.loan; })
      .sort(function (a, b) { return a.name.localeCompare(b.name); });
    if (!loaned.length) { section.style.display = 'none'; return; }

    loaned.forEach(function (p) {
      var card = el('div', 'loan-watch-card');
      card.appendChild(media('loan-watch-media', p, false));
      var body = el('div', 'loan-watch-body');
      body.appendChild(el('div', 'loan-watch-name', esc(p.name)));
      body.appendChild(el('div', 'loan-watch-meta', esc(positionLabel(p)) + ' &middot; ' + p.age + ' yrs &middot; ' + p.ovr + ' OVR'));
      body.appendChild(el('div', 'loan-watch-club', 'On loan: ' + esc(p.loan.club)));
      if (p.loan.back) body.appendChild(el('div', 'loan-watch-back', 'Back ' + esc(p.loan.back)));
      card.appendChild(body);
      root.appendChild(card);
    });
  }

  /* ── Squad Intelligence ────────────────────────────────────────────── */
  function renderIntelligence(root, data) {
    var players = data.players;

    // Age Profile
    var ageBuckets = [
      ['U21', function (a) { return a <= 21; }],
      ['22–25', function (a) { return a >= 22 && a <= 25; }],
      ['26–29', function (a) { return a >= 26 && a <= 29; }],
      ['30+', function (a) { return a >= 30; }],
    ];
    var ageCard = el('div', 'squad-intel-card');
    ageCard.appendChild(el('div', 'squad-intel-title', 'Age Profile'));
    var maxAgeCount = Math.max.apply(null, ageBuckets.map(function (b) {
      return players.filter(function (p) { return b[1](p.age); }).length;
    }));
    ageBuckets.forEach(function (b) {
      var count = players.filter(function (p) { return b[1](p.age); }).length;
      var row = el('div', 'squad-intel-row');
      row.appendChild(el('span', 'squad-intel-row-label', b[0]));
      var bar = el('div', 'squad-intel-bar');
      var fill = el('div', 'squad-intel-bar-fill');
      fill.style.width = (maxAgeCount ? (count / maxAgeCount * 100) : 0) + '%';
      bar.appendChild(fill);
      row.appendChild(bar);
      row.appendChild(el('span', 'squad-intel-row-count', count));
      ageCard.appendChild(row);
    });
    root.appendChild(ageCard);

    // OVR Distribution
    var ovrCard = el('div', 'squad-intel-card');
    ovrCard.appendChild(el('div', 'squad-intel-title', 'OVR Distribution'));
    var ovrs = players.map(function (p) { return p.ovr; });
    var facts = [
      ['Average', data.glance.avgOvr],
      ['Highest', Math.max.apply(null, ovrs) + ' (' + data.glance.highestOvr + ')'],
      ['Lowest', Math.min.apply(null, ovrs)],
      ['Range', (Math.max.apply(null, ovrs) - Math.min.apply(null, ovrs)) + ' pts'],
    ];
    facts.forEach(function (f) {
      var row = el('div', 'squad-intel-fact');
      row.appendChild(el('span', 'squad-intel-fact-label', f[0]));
      row.appendChild(el('span', 'squad-intel-fact-value is-gold', f[1]));
      ovrCard.appendChild(row);
    });
    root.appendChild(ovrCard);

    // Development Watch: young players with a stored potential range
    var devCard = el('div', 'squad-intel-card');
    devCard.appendChild(el('div', 'squad-intel-title', 'Development Watch'));
    var prospects = players.filter(function (p) { return p.potential && p.age <= 22; })
      .sort(function (a, b) { return a.age - b.age; })
      .slice(0, 6);
    if (prospects.length) {
      var list = el('div', 'squad-intel-dev-list');
      prospects.forEach(function (p) {
        var row = el('div', 'squad-intel-dev-item');
        row.appendChild(el('span', 'squad-intel-dev-name', esc(p.name) + ' <span style="color:var(--muted)">&middot; ' + p.age + '</span>'));
        row.appendChild(el('span', 'squad-intel-dev-pot', 'POT ' + esc(p.potential)));
        list.appendChild(row);
      });
      devCard.appendChild(list);
    } else {
      devCard.appendChild(el('div', 'squad-intel-empty', 'No stored potential ranges for current U22 first-teamers.'));
    }
    root.appendChild(devCard);
  }

  /* ── Squad Leaders ──────────────────────────────────────────────────── */
  function leaderList(root, entries, valueLabel) {
    entries.slice(0, 5).forEach(function (p, i) {
      var row = el('div', 'squad-leader-row');
      row.appendChild(el('span', 'squad-leader-rank', i + 1));
      var photo = el('div', 'squad-leader-photo');
      if (p.image) {
        var img = el('img'); img.src = p.image; img.alt = p.name; img.loading = 'lazy';
        photo.appendChild(img);
      }
      row.appendChild(photo);
      var nameWrap = el('span', 'squad-leader-name', esc(p.name));
      row.appendChild(nameWrap);
      row.appendChild(el('span', 'squad-leader-pos', esc(p.positions.join('/'))));
      row.appendChild(el('span', 'squad-leader-value', p.value + valueLabel));
      root.appendChild(row);
    });
  }

  function renderLeaders(section, data) {
    var l = data.leaders;
    if (!l.goals.length && !l.assists.length) { section.style.display = 'none'; return; }

    var grid = el('div', 'squad-leaders-grid');

    if (l.goals.length) {
      var goalsCol = el('div', 'squad-leaders-col');
      goalsCol.appendChild(el('div', 'squad-leaders-col-head', 'Goals'));
      leaderList(goalsCol, l.goals, '');
      grid.appendChild(goalsCol);
    }
    if (l.assists.length) {
      var assistsCol = el('div', 'squad-leaders-col');
      assistsCol.appendChild(el('div', 'squad-leaders-col-head', 'Assists'));
      leaderList(assistsCol, l.assists, '');
      grid.appendChild(assistsCol);
    }
    section.appendChild(grid);
  }

  /* ── Boot ───────────────────────────────────────────────────────────── */
  document.addEventListener('DOMContentLoaded', function () {
    if (typeof SQUAD_DATA === 'undefined') return;
    var data = SQUAD_DATA;

    var eyebrow = document.getElementById('squad-eyebrow');
    if (eyebrow) eyebrow.textContent = 'Wrexham AFC · ' + data.season + ' ' + data.competition + ' Squad';

    var introEl = document.getElementById('squad-intro');
    if (introEl && typeof SQUAD_CONFIG !== 'undefined') introEl.textContent = SQUAD_CONFIG.intro;

    if (typeof SQUAD_CONFIG !== 'undefined') {
      var heroImg = document.getElementById('squad-hero-img');
      var heroCap = document.getElementById('squad-hero-caption');
      var heroMedia = document.getElementById('squad-hero-media');
      if (heroImg) {
        heroImg.src = SQUAD_CONFIG.hero.image;
        heroImg.alt = SQUAD_CONFIG.hero.imageAlt;
      }
      if (heroCap) heroCap.textContent = SQUAD_CONFIG.hero.caption;
      if (heroMedia) {
        heroMedia.style.setProperty('--squad-hero-focus-x', SQUAD_CONFIG.hero.focusX);
        heroMedia.style.setProperty('--squad-hero-focus-y', SQUAD_CONFIG.hero.focusY);
      }
    }

    var glanceRoot = document.getElementById('squad-glance');
    if (glanceRoot) renderGlance(glanceRoot, data);

    var featuredRoot = document.getElementById('squad-feature');
    if (featuredRoot) renderFeatured(featuredRoot, data);

    var groupsRoot = document.getElementById('squad-groups');
    if (groupsRoot) renderGroups(groupsRoot, data);

    var loanSection = document.getElementById('loan-watch-section');
    var loanRoot = document.getElementById('loan-watch-grid');
    if (loanSection && loanRoot) renderLoanWatch(loanSection, loanRoot, data);

    var intelRoot = document.getElementById('squad-intel-grid');
    if (intelRoot) renderIntelligence(intelRoot, data);

    var leadersSection = document.getElementById('squad-leaders-section');
    if (leadersSection) renderLeaders(leadersSection, data);
  });
})();
